/**
 * native messaging host 的安装 —— **纯计划 / 落地**两段，路径全来自 `layout`。
 *
 * 为什么这么拆：
 *   1. `planNativeHostInstall()` 是**纯函数**（只算路径与文件内容，不碰磁盘）⇒
 *      dry-run 能把它原样打印给用户看，单测也能断言 → 不需要真的写到用户的
 *      `~/Library/Application Support/...` 去验证；
 *   2. 平台差异（macOS/Linux 是清单文件、Windows 是注册表）收在 `layout` 一处；
 *   3. `native-host/install.mjs` 与 `bootstrap/install.mjs` 都调这里，不再各写一份。
 *
 * 历史包袱（本轮修掉的）：老的 `native-host/install.mjs` 把 Chrome 目录写死成 macOS 的，
 * 并且把生成物 `run-host.sh`（内含**本机** node 与仓库绝对路径）提交进了 git。
 */
import { mkdirSync, writeFileSync, chmodSync, rmSync, existsSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { HOST_NAME, chromeNativeMessagingCandidates, pickChromeTarget } from './layout.mjs'

/** 拉起器脚本内容（路径来自参数，绝不写死）。 */
export function runnerScript({ nodePath, hostEntry }) {
  return `#!/bin/sh
# Generated by bootstrap/install.mjs — launches the DSH Web Companion native host.
# 这个文件含**本机**的 node 与安装路径，故不入版本库（见 .gitignore）。
exec "${nodePath}" "${hostEntry}"
`
}

/** native messaging 清单内容。 */
export function hostManifest({ extensionId, runnerPath }) {
  return {
    name: HOST_NAME,
    description: 'DSH Web Companion host: starts and inspects the local dsh web server',
    path: runnerPath,
    type: 'stdio',
    allowed_origins: [`chrome-extension://${extensionId}/`],
  }
}

/**
 * 算出"要写哪些文件、内容是什么"，不落盘。
 *
 * @param {object} layout        resolveLayout() 的结果
 * @param {object} opts
 * @param {string} opts.extensionId
 * @param {string} opts.nodePath     要钉进 run-host.sh 的 node（默认当前进程）
 * @param {(dir: string) => boolean} [opts.exists]
 */
export function planNativeHostInstall(layout, opts) {
  const { extensionId, nodePath = process.execPath, exists = existsSync } = opts ?? {}
  if (typeof extensionId !== 'string' || extensionId === '') throw new TypeError('planNativeHostInstall: 需要 extensionId')

  const candidates = chromeNativeMessagingCandidates({ platform: layout.platform, homeDir: layout.homeDir })
  const target = pickChromeTarget(candidates, exists)
  const chromeDir = Array.isArray(candidates) ? target.dir : null

  return {
    hostName: HOST_NAME,
    runnerPath: layout.runner,
    runnerBody: runnerScript({ nodePath, hostEntry: layout.nativeHostEntry }),
    /*
     * ★ 用 `join()` 拼，不再写字面量 `/`（2026-09-13 修；PiMoa 片 2 第 4 条）：
     * 同一个清单路径原来在这里和 `layout` 里各拼一遍，分隔符硬编码 ⇒ dry-run 展示的
     * 与实际要写的可以是两个不同的字符串（"路径唯一真源"被破坏）。
     */
    manifestPath: chromeDir === null ? null : join(chromeDir, `${HOST_NAME}.json`),
    manifest: hostManifest({ extensionId, runnerPath: layout.runner }),
    chromeDir,
    browser: Array.isArray(candidates) ? target.browser ?? null : null,
    /** 非数组 ⇒ 该平台不是"写清单文件"那一类（Windows 走注册表）。本项目**只支持 macOS**。 */
    registry: Array.isArray(candidates) ? null : candidates,
  }
}

/** 给用户看的一行行"将要发生什么"（dry-run 与实装前的确认都用它）。 */
export function describeNativeHostPlan(plan) {
  const lines = [
    `写拉起器脚本   ${plan.runnerPath}`,
    `写 Chrome 清单 ${plan.manifestPath ?? '(Windows 需写注册表，本项目暂不支持)'}`,
    `  清单内容     name=${plan.hostName} allowed_origins=${plan.manifest.allowed_origins.join(',')}`,
  ]
  if (plan.browser !== null) lines.push(`  目标浏览器   ${plan.browser}`)
  return lines
}

/** 真正落盘。返回写过的文件清单，便于卸载时反向。 */
export function applyNativeHostInstall(plan) {
  /*
   * ★ `manifestPath === null` 时**必须报错**，不许"正常返回"（2026-09-13 修；PiMoa 片 2 第 6 条）。
   *
   * 原来这里直接 `if (plan.manifestPath !== null) {...}` 就结束了：非 macOS（Windows 走注册表、
   * 其它平台未验证）会**静默跳过写清单**并返回成功 ⇒ 正面违反用户那条「Windows 可以不做，
   * 但不许假装成功」。本项目**只支持 macOS**，所以这里把话说死、当场停下。
   */
  if (plan.manifestPath === null) {
    throw new Error('这只支持 macOS：Chrome 的 native messaging 清单路径不存在（Windows 需写注册表，其它平台未验证）。与其假装成功，这里直接报错。')
  }
  const written = []
  mkdirSync(dirname(plan.runnerPath), { recursive: true })
  writeFileSync(plan.runnerPath, plan.runnerBody)
  chmodSync(plan.runnerPath, 0o755)
  written.push(plan.runnerPath)
  mkdirSync(dirname(plan.manifestPath), { recursive: true })
  writeFileSync(plan.manifestPath, `${JSON.stringify(plan.manifest, null, 2)}\n`)
  written.push(plan.manifestPath)
  return written
}

/** 卸载：只删清单（拉起器随安装目录一起删）。 */
export function removeNativeHostManifest(plan) {
  if (plan.manifestPath === null) return []
  rmSync(plan.manifestPath, { force: true })
  return [plan.manifestPath]
}
